#!/usr/bin/env python3
"""Independent reference for bounded skin/shadow refinements, never a RAW calibration.

Original stock resources stay byte-identical. The app bakes this mapping once into
its shared look cube before user curves/WB composition. This tool predicts probes
and writes XCTest reference values; actual before/after photographs come from CI.
"""
from __future__ import annotations

import argparse
import json
import struct
from pathlib import Path

import numpy as np

from audit_film_scenes import FILMS, ROOT, read_compiled, sample

LUMA = np.array([0.2126, 0.7152, 0.0722])


def smooth(lo, hi, value):
    x = np.clip((value - lo) / (hi - lo), 0, 1)
    return x * x * (3 - 2 * x)


def chroma(rgb):
    y = rgb @ LUMA
    return y, np.stack([(rgb[..., 2] - y) / 1.8556, (rgb[..., 0] - y) / 1.5748], -1)


def refine(rgb, graded, profile):
    """Encoded-sRGB Y'/Cb/Cr, input-gated; no semantic face detection or AWB."""
    y, uv = chroma(rgb)
    out_y, out_uv = chroma(graded)
    source_c = np.linalg.norm(uv, axis=-1)
    out_c = np.linalg.norm(out_uv, axis=-1)
    ratio = -uv[..., 0] / np.maximum(uv[..., 1], 1e-6)
    skin = (smooth(.35, .55, ratio) * (1 - smooth(1.10, 1.40, ratio))
            * smooth(.005, .025, uv[..., 1]) * (1 - smooth(-.015, .005, uv[..., 0]))
            * smooth(.015, .045, source_c) * (1 - smooth(.20, .28, source_c))
            * smooth(.025, .07, y) * (1 - smooth(.80, .98, y)))
    direction = uv / np.maximum(source_c[..., None], 1e-6)
    pulled = out_uv + skin[..., None] * profile["skinHue"] * (direction * out_c[..., None] - out_uv)
    pulled *= (out_c / np.maximum(np.linalg.norm(pulled, axis=-1), 1e-6))[..., None]
    excess = np.maximum(0, out_c - source_c * 1.35)
    target_c = np.maximum(0, out_c - excess * skin * profile["skinChroma"])
    pulled *= (target_c / np.maximum(out_c, 1e-6))[..., None]
    shadow = np.maximum(0, y * profile["shadowRetention"] - out_y) * (1 - smooth(.15, .40, y))
    skin_lift = np.maximum(0, y - out_y) * skin * profile["skinLightness"]
    luminance = out_y + np.maximum(shadow, skin_lift)
    red = luminance + 1.5748 * pulled[..., 1]
    blue = luminance + 1.8556 * pulled[..., 0]
    green = (luminance - .2126 * red - .0722 * blue) / .7152
    result = np.clip(np.stack([red, green, blue], -1), 0, 1)
    # Preserve source samples exactly where no correction is active.
    unchanged = (skin == 0) & (shadow == 0)
    return np.where(unchanged[..., None], graded, result)


def refined_table(table, profile):
    axis = np.linspace(0, 1, len(table))
    b, g, r = np.meshgrid(axis, axis, axis, indexing="ij")
    return refine(np.stack([r, g, b], -1), table, profile)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--swift-reference", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    config = json.loads((ROOT / "JustShoot/Resources/FilmLookRefinements.json").read_text())
    probes = np.array([[0, 0, 0], [1, 1, 1], [.78, .59, .48], [.55, .39, .30],
                       [.30, .19, .12], [.14, .09, .06], [.02, .02, .02], [.05, .05, .05],
                       [.10, .10, .10], [.2, .2, .2], [.4, .4, .4], [.75, .75, .75],
                       [.15, .45, .18], [.3, .6, .95], [.9, .04, .09], [.1, .9, .9]])
    report = {"revision": config["revision"], "scope": "Independent synthetic mapping reference; not measured skin/film truth", "looks": []}
    for identifier, resource, label in FILMS:
        table = read_compiled(ROOT / "JustShoot/Resources" / (resource + ".jslut"))
        profile = config["profiles"][identifier]
        refined = refined_table(table, profile)
        before = sample(table, probes)
        after = sample(refined, probes)
        report["looks"].append({"id": identifier, "label": label, "dimension": len(table),
            "profile": profile, "samples": [{"input": a.tolist(), "before": b.tolist(), "after": c.tolist()} for a, b, c in zip(probes, before, after)]})
        rgba = np.concatenate([refined, np.ones(refined.shape[:-1] + (1,))], -1).astype("<f4")
        (args.output / (identifier + ".jslut")).write_bytes(struct.pack("<8sII", b"JSLUT001", len(table), rgba.size) + rgba.tobytes())
    (args.output / "reference.json").write_text(json.dumps(report, indent=2) + "\n")
    if args.swift_reference:
        lines = ["// Generated by scripts/refine_film_looks.py; independent double-precision reference.",
                 "@testable import JustShoot", "", "enum FilmLookRefinementReference {",
                 "    struct Sample {", "        let film: FilmPreset", "        let input: SIMD3<Float>",
                 "        let output: SIMD3<Float>", "    }", "    static let samples: [Sample] = ["]
        def vector(v):
            return "SIMD3(" + ", ".join(format(float(n), ".9g") for n in v) + ")"
        for look in report["looks"]:
            for index in (2, 3, 4, 6, 8, 13):
                item = look["samples"][index]
                lines.append(f"        Sample(film: .{look['id']}, input: {vector(item['input'])}, output: {vector(item['after'])}),")
        lines += ["    ]", "}", ""]
        args.swift_reference.write_text("\n".join(lines))
    print(json.dumps({"looks": len(report["looks"]), "output": str(args.output)}))


if __name__ == "__main__":
    main()
